import type { ApiArtifact } from "./api";

interface Ticket {
  id: string;
  title: string;
  objective: string;
  non_goals: string[];
  acceptance_criteria: string[];
  test_requirements: string[];
  depends_on: string[];
  estimated_size: string;
}

// Injection guard: AI-generated ticket text is untrusted before it reaches the
// user's own coding tool. Flag URLs and imperative override patterns so the
// user reviews them before pasting into Cursor/Lovable against their codebase.
const SUSPICIOUS =
  /ignore (all|any|previous|prior)|disregard (the|all|previous)|exfiltrat|curl |wget |https?:\/\//i;

function ticketText(t: Ticket): string {
  return [
    t.title,
    t.objective,
    ...t.non_goals,
    ...t.acceptance_criteria,
    ...t.test_requirements,
  ].join("\n");
}

export function buildPromptPack(backlog: ApiArtifact, projectName: string): string {
  const tickets = (backlog.content.tickets as Ticket[]) ?? [];
  const note = (backlog.content.build_sequence_note as string) ?? "";
  const flagged = tickets.filter((t) => SUSPICIOUS.test(ticketText(t)));

  const lines: string[] = [
    `# ${projectName} - AI build prompt pack`,
    "",
    `Generated by Verdict from "${backlog.title}" (produced by ${backlog.agent_slug}).`,
    "Paste one prompt at a time into Lovable, Cursor, Claude Code, or Replit.",
    "Complete and verify each ticket before starting the next.",
    "",
  ];

  if (flagged.length > 0) {
    lines.push(
      "> **REVIEW BEFORE PASTING.** These tickets contain links or unusual",
      "> instructions and are marked [FLAGGED] below. AI-generated text can",
      "> carry injected instructions - read them before running them against",
      `> your codebase: ${flagged.map((t) => t.id).join(", ")}`,
      ""
    );
  }

  lines.push(`**Build order note:** ${note}`, "", "---", "");

  for (const t of tickets) {
    const isFlagged = flagged.includes(t);
    lines.push(
      `## ${t.id}: ${t.title} (size ${t.estimated_size})${isFlagged ? " [FLAGGED]" : ""}`,
      ""
    );
    if (isFlagged) {
      lines.push(
        "**[FLAGGED] Review this ticket's text carefully before pasting.**",
        ""
      );
    }
    lines.push(
      "```text",
      `You are implementing one ticket of a larger plan. Do ONLY this ticket.`,
      ``,
      `Objective: ${t.objective}`,
      ``,
      `Do NOT do any of the following (explicit non-goals):`,
      ...t.non_goals.map((n) => `- ${n}`),
      ``,
      `Acceptance criteria (all must pass):`,
      ...t.acceptance_criteria.map((c) => `- ${c}`),
      ``,
      `Required tests:`,
      ...t.test_requirements.map((r) => `- ${r}`),
      ``,
      t.depends_on.length
        ? `This ticket depends on: ${t.depends_on.join(", ")} - assume they are complete.`
        : `This ticket has no dependencies.`,
      ``,
      `When done, list what you changed and how you verified each acceptance criterion.`,
      "```",
      ""
    );
  }
  return lines.join("\n");
}
